<h1>Batman: Arkham Knight</h1>
    <p1> Batman: Arkham Knight (с англ. — «Бэтмен: Рыцарь Аркхэма») — компьютерная игра в жанре action-adventure в открытом мире с элементами стелса, разработанная британской студией Rocksteady Studios и изданная американской компанией Warner Bros. Interactive Entertainment. Игра основана на комиксах DC Comics о Бэтмене и является четвёртой частью франшизы Batman: Arkham, продолжая игру Batman: Arkham City 2011 года. Сценарий для неё написали Сефтон Хилл, Йен Болл и Мартин Ланкастер. Действия Arkham Knight разворачиваются спустя девять месяцев после событий Arkham City, а главным злодеем является Пугало, который объявил о токсиновой атаке на Готэм-Сити, вызвав массовую эвакуацию населения, и с помощью таинственного Рыцаря Аркхэма решил объединить всех опасных злодеев города с целью уничтожить Бэтмена</p1>
